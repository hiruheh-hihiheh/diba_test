// supabase/functions/_selftest/test-copies.ts
//
// Acceptance test for FLEXIBLE COPY HANDLING: a workbook may carry one, two or
// three physical print copies of an invoice, and the output is always all three.
//
// The rule under test, stated once:
//   ONE PHYSICAL INVOICE = ONE BILL RECORD = THREE PRINTABLE COPY PDFs.
//
// So the checks come in three groups.
//
//   A. THE SIX SOURCE SHAPES plus all-three — every combination of which copy
//      blocks the workbook contains must yield one bill carrying all three
//      documents, with the right label on each and identical financial content.
//
//   B. SYNTHESIS FIDELITY — a generated copy must differ from its canonical in
//      the copy label and in nothing else, and must be an independent object:
//      mutating one must not be visible through the others. A shallow clone
//      passes every "identical?" check and still corrupts the second document.
//
//   C. PER-SHEET, NOT PER-WORKBOOK — a workbook mixing a single-copy sheet with a
//      three-copy sheet, and the sheet that arrives with only DUPLICATE or only
//      TRIPLICATE, which is the case a naive "read the ORIGINAL block" parser
//      gets wrong.
//
// Plus the real workbooks: `SAMPLE.xlsx` and the 20-sheet production workbook,
// and the SANITIZED single-copy fixture — generated by `make-fixture.ts` from the
// real acceptance workbook's layout with every identifying value replaced, because
// a customer's name, address, GST numbers and bank account do not belong in a
// repository. Its structure and arithmetic are the real workbook's.
