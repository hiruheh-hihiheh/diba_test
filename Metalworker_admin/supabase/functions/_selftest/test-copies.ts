section("A. one bill and three documents from every source shape");

/* The single-copy fixture. Sanitized — see the header note — but structurally the
   real thing: one sheet, ORIGINAL only, one invoice, the full reference block, the
   bank block and the four footer rows. */
const single = (await readXlsx(readFileSync(resolve(REPO, "test-bills-sanitized.xlsx")))).sheets[0];
const singleCells = single.cells.size;

/* The fixture's identifying values, so the assertions name them once and a change
   to the generator is a one-line fix here rather than a search. */
const F = {
  invoiceNo: "TEST/001/2026-27",
  orderNo: "TEST/SO/2600001",
  partyChallan: "TEST/OGC/TR/2600001",
  party: "M/s. Sample Traders Ltd.,",
  seller: "EXAMPLE ENGINEERING WORKS",
  qty: 1,
  rate: 9000,
  beforeTax: 9000,
  cgst: 810,
  sgst: 810,
  igst: 0,
  totalGst: 1620,
  afterTax: 10620,
} as const;

/* Each shape is a REAL invoice sheet carrying only the blocks named. A single-copy
   shape is made by relabelling the sheet's one block, since on this sheet the
   ORIGINAL block spans everything. */
const SHAPES: { keep: CopyKind[]; title: string; build: () => Sheet }[] = [
  { keep: ["original"], title: "ORIGINAL only", build: () => single },
  { keep: ["duplicate"], title: "DUPLICATE only", build: () => labelledAs(single, "duplicate") },
  { keep: ["triplicate"], title: "TRIPLICATE only", build: () => labelledAs(single, "triplicate") },
  { keep: ["original", "duplicate"], title: "ORIGINAL + DUPLICATE", build: () => withExtraCopy(single, "duplicate") },
  { keep: ["original", "triplicate"], title: "ORIGINAL + TRIPLICATE", build: () => withExtraCopy(single, "triplicate") },
  {
    keep: ["duplicate", "triplicate"],
    title: "DUPLICATE + TRIPLICATE",
    build: () => withExtraCopy(labelledAs(single, "duplicate"), "triplicate"),
  },
  {
    keep: ALL,
    title: "ORIGINAL + DUPLICATE + TRIPLICATE",
    build: () => withExtraCopy(withExtraCopy(single, "duplicate"), "triplicate"),
  },
];

/* Parsed once here and re-used by group B, so the two groups cannot disagree. */
const parsedByShape = new Map<string, ReturnType<typeof parseSheet>>();

for (const shape of SHAPES) {
  const sheet = shape.build();
  const bill = parseSheet(sheet);
  parsedByShape.set(shape.title, bill);

  const present = findCopyBlocks(sheet).map((b) => b.kind).sort();
  check(
    present.join(",") === [...shape.keep].sort().join(","),
    `${shape.title}: fixture really carries ${present.join(", ") || "(none)"}`,
    present.join(", ")
  );

  /* THE CENTRAL RULE: one worksheet is one bill, never three. */
  check(
    bill.original !== null && bill.duplicate !== null && bill.triplicate !== null,
    `${shape.title}: parse yields all three BillCopy objects`
  );

  /* Canonical selection: ORIGINAL > DUPLICATE > TRIPLICATE. */
  const expectedCanonical = ALL.find((k) => shape.keep.includes(k))!;
  check(
    bill.canonicalKind === expectedCanonical,
    `${shape.title}: canonical is ${COPY_LABEL[expectedCanonical]}`,
    `got ${COPY_LABEL[bill.canonicalKind]}`
  );

  /* `sourceCopies` must describe the WORKBOOK, not the parse result. */
  check(
    bill.sourceCopies.join(",") === [...shape.keep].sort((a, b) => ALL.indexOf(a) - ALL.indexOf(b)).join(","),
    `${shape.title}: sourceCopies reports only what the workbook held`,
    bill.sourceCopies.join(", ")
  );

  /* Every copy carries its own correct output label — the single most visible
     way this feature can go wrong: three PDFs that all say ORIGINAL. */
  for (const kind of ALL) {
    check(
      bill[kind].label === COPY_LABEL[kind] && bill[kind].kind === kind,
      `${shape.title}: ${kind} is labelled ${COPY_LABEL[kind]}`,
      `got "${bill[kind].label}"`
    );
  }

  /* The generated documents must actually SAY it, not just carry it in the model. */
  for (const kind of ALL) {
    const text = pdfText(renderBillDocument([bill[kind]], COPY_LABEL[kind]));
    check(
      new RegExp(`\\b${COPY_LABEL[kind]}\\b`).test(text),
      `${shape.title}: rendered ${kind}.pdf prints ${COPY_LABEL[kind]}`
    );
  }

  /* The financial figures survive whichever copy was the source. */
  const o = bill[expectedCanonical];
  check(
    o.invoiceNo === F.invoiceNo,
    `${shape.title}: invoice number is ${F.invoiceNo}`,
    String(o.invoiceNo)
  );
  check(
    o.amountBeforeTax === F.beforeTax && o.cgst === F.cgst && o.sgst === F.sgst &&
      o.igst === F.igst && o.totalGst === F.totalGst && o.amountAfterTax === F.afterTax,
    `${shape.title}: 9,000 + 1,620 GST = 10,620`,
    `${o.amountBeforeTax} + ${o.cgst}/${o.sgst}/${o.igst} = ${o.amountAfterTax}`
  );
  check(
    o.jobKind === "LABOUR JOB",
    `${shape.title}: job type is LABOUR JOB`,
    String(o.jobKind)
  );
  check(
    o.lineItems.length === 1 && o.lineItems[0].amount === F.rate && o.lineItems[0].rate === F.rate,
    `${shape.title}: the line item survived (1 x 9,000)`
  );
  check(
    o.bankLines.length > 0 && o.termsLines.length > 0 && o.signatureLines.length > 0,
    `${shape.title}: bank, terms and signature blocks survived`,
    `bank=${o.bankLines.length} terms=${o.termsLines.length} sig=${o.signatureLines.length}`
  );
  check(
    o.referenceRows.length > 0,
    `${shape.title}: the reference block (incl. blank rows) survived`,
    `${o.referenceRows.length} rows`
  );
}

/* A DUPLICATE-only or TRIPLICATE-only workbook has no ORIGINAL at all. That is
   the shape a "read the ORIGINAL block" parser gets catastrophically wrong, so
   it is asserted separately and loudly. */
for (const kind of ["duplicate", "triplicate"] as CopyKind[]) {
  const bill = parsedByShape.get(kind === "duplicate" ? "DUPLICATE only" : "TRIPLICATE only")!;
  const blocks = findCopyBlocks(labelledAs(single, kind));
  check(
    blocks.length === 1 && !blocks.some((b) => b.kind === "original"),
    `${COPY_LABEL[kind]}-only: the workbook has no ORIGINAL block at all`
  );
  check(
    bill.original.invoiceNo === F.invoiceNo,
    `${COPY_LABEL[kind]}-only: its data became the ORIGINAL document`
  );
  check(
    bill.original.label === "ORIGINAL",
    `${COPY_LABEL[kind]}-only: the generated original is labelled ORIGINAL, not ${COPY_LABEL[kind]}`
  );
}

/* ──────────────────────────────────────────────
   B. Synthesis fidelity and clone independence
   ────────────────────────────────────────────── */

section("B. a generated copy differs from its canonical only by the label");

/* Which fields are the copy's IDENTITY rather than the invoice's content. The
   designation and its kind are OUTPUT properties — that is the entire intended
   difference. Everything else, including the row span, must match. */
const IDENTITY_FIELDS = new Set<keyof BillCopy>(["kind", "label"]);

for (const shape of SHAPES) {
  const bill = parsedByShape.get(shape.title)!;
  for (const kind of ALL) {
    if (shape.keep.includes(kind)) continue; // a parsed copy is not synthesized
    const canonical = bill[bill.canonicalKind];

    const diffs = (Object.keys(canonical) as (keyof BillCopy)[]).filter(
      (k) => !IDENTITY_FIELDS.has(k) && JSON.stringify(canonical[k]) !== JSON.stringify(bill[kind][k])
    );
    check(
      diffs.length === 0,
      `${shape.title}: generated ${kind} matches ${COPY_LABEL[bill.canonicalKind]} on every other field`,
      diffs.join(", ")
    );

    /* The label really is the only visible difference on the page. Comparing the
       rendered text with the label removed is the check a reviewer would make by
       eye, done mechanically. */
    const strip = (t: string) => t.split("\n").filter((line) => line.trim() !== COPY_LABEL[kind]).join("\n");
    check(
      strip(pdfText(renderBillDocument([bill[kind]], COPY_LABEL[kind]))) ===
        strip(pdfText(renderBillDocument([canonical], COPY_LABEL[kind]))),
      `${shape.title}: generated ${kind}.pdf is identical to the canonical except the label`
    );
  }
}

section("B2. the three copies are independent objects");

/* A shallow `{ ...canonical }` passes every comparison in group B and still shares
   the line-item and bank arrays, so an edit through one document's model would
   silently rewrite the other two. This is the check that fails for a shallow clone.

   Each copy is mutated on its OWN freshly parsed bill: sharing would then be
   indistinguishable from leakage, and the test would pass for the wrong reason. */
{
  const pristine = parsedByShape.get("ORIGINAL only")!;

  for (const kind of ALL) {
    const bill = parseSheet(single);
    const snapshot = new Map(ALL.map((k) => [k, JSON.stringify(bill[k])]));
    const fields = arrayFields(bill[kind]);

    check(
      Object.keys(fields).length >= 8,
      `${kind}: has every array field worth testing for sharing`,
      `${Object.keys(fields).length}: ${Object.keys(fields).join(", ")}`
    );

    /* Push into each array AND into its first object: a clone that copies the
       array but not the elements fails the second half. */
    for (const [name, arr] of Object.entries(fields)) {
      arr.push(`__mutated_${kind}_${name}`);
      const first = arr[0];
      if (first !== null && typeof first === "object") {
        (first as Record<string, unknown>).__mutated = true;
      }
    }

    const alsoMoved = ALL.filter((k) => k !== kind && snapshot.get(k) !== JSON.stringify(bill[k]));
    check(
      alsoMoved.length === 0,
      `${kind}: mutating its arrays and elements left the other two copies byte-identical`,
      alsoMoved.join(", ")
    );
    check(
      snapshot.get(kind) !== JSON.stringify(bill[kind]),
      `${kind}: the mutation really did land on the copy under test`
    );
    check(
      snapshot.get("original") === JSON.stringify(pristine.original),
      `${kind}: the original still equals a freshly parsed one`
    );
  }

  /* Object identity is the actual question: two arrays can compare equal right up
     until one of them changes, so equality alone does not settle sharing. */
  const bill = parseSheet(single);
  const shared: string[] = [];
  for (const [i, a] of ALL.entries()) {
    for (const b of ALL.slice(i + 1)) {
      for (const name of Object.keys(arrayFields(bill[a]))) {
        if (arrayFields(bill[a])[name] === arrayFields(bill[b])[name]) shared.push(`${a}/${b}:${name}`);
      }
    }
  }
  check(shared.length === 0, "no array object is shared between any two copies", shared.join(", "));

  const texts = ALL.map((k) => pdfText(renderBillDocument([bill[k]], COPY_LABEL[k])));
  const bare = (t: string) => t.replace(/\b(ORIGINAL|DUPLICATE|TRIPLICATE)\b/g, "");
  check(
    texts.every((t) => bare(t) === bare(texts[0])),
    "all three documents render identically apart from the copy label"
  );
}

{
  /* `synthesizeCopy` is exported, so its contract is tested directly too: given a
     copy, produce an independent object with the requested identity. */
  const canonical = parsedByShape.get("ORIGINAL only")!.original;
  const clone = synthesizeCopy(canonical, "triplicate");
  check(clone !== canonical, "synthesizeCopy returns a new object");
  check(clone.kind === "triplicate" && clone.label === "TRIPLICATE", "synthesizeCopy stamps the requested identity");
  check(clone.lineItems !== canonical.lineItems, "synthesizeCopy deep-clones lineItems");
  check(
    JSON.stringify({ ...clone, kind: 0, label: 0 }) === JSON.stringify({ ...canonical, kind: 0, label: 0 }),
    "synthesizeCopy is otherwise value-identical"
  );
}

/* ──────────────────────────────────────────────
   C. Per sheet, not per workbook
   ────────────────────────────────────────────── */

section("C. copy presence is decided per SHEET");

/* A real mixed workbook, written out as a real .xlsx and read back through the
   same reader the edge function uses — not a hand-assembled Sheet[]. */
{
  const mixed = writeXlsx([
    { ...single, name: "OnlyOriginal" },
    { ...withExtraCopy(withExtraCopy(single, "duplicate"), "triplicate"), name: "AllThree" },
    { ...labelledAs(single, "duplicate"), name: "OnlyDuplicate" },
  ]);

  const wb = await readXlsx(mixed);
  check(wb.sheets.length === 3, "the mixed workbook really has three sheets", `${wb.sheets.length}`);

  const { bills, skipped } = parseBills(wb.sheets);
  check(skipped.length === 0, "no sheet in the mixed workbook was skipped", skipped.map((s) => s.reason).join("; "));
  check(bills.length === 3, "three sheets -> three bills, not nine", `${bills.length}`);

  const byName = new Map(bills.map((b) => [b.sheetName, b]));
  check(
    byName.get("OnlyOriginal")?.sourceCopies.join(",") === "original",
    "sheet A reports one source copy"
  );
  check(
    byName.get("AllThree")?.sourceCopies.join(",") === "original,duplicate,triplicate",
    "sheet B reports three source copies",
    byName.get("AllThree")?.sourceCopies.join(", ")
  );
  check(
    byName.get("OnlyDuplicate")?.canonicalKind === "duplicate",
    "sheet C takes DUPLICATE as its canonical"
  );

  /* Nine documents, three per bill, and every bill still holds one invoice's
     money — this is the "do not multiply by 3" requirement. */
  const total = bills.reduce((n, b) => n + (b.original.amountAfterTax ?? 0), 0);
  check(
    total === F.afterTax * 3,
    "totals are counted once per bill (3 bills x 10,620)",
    String(total)
  );
  check(
    bills.every((b) => b.original.amountAfterTax === F.afterTax),
    "no bill's total was tripled by generating its copies"
  );

  /* Each copy of a sheet that HAD the block still comes from that block. */
  const allThree = byName.get("AllThree")!;
  check(
    allThree.duplicate.label === "DUPLICATE" && allThree.triplicate.label === "TRIPLICATE",
    "a three-copy sheet keeps its own parsed blocks, not clones"
  );

  /* The aggregate documents: one page per recognised sheet, in worksheet order,
     which is what the workbook-level PDFs are. */
  for (const kind of ALL) {
    const bytes = renderBillDocument(bills.map((b) => b[kind]), COPY_LABEL[kind]);
    const pages = (new TextDecoder("latin1").decode(bytes).match(/\/Type\s*\/Page[^s]/g) ?? []).length;
    check(pages === 3, `aggregate ${kind}.pdf has one page per sheet (3)`, `${pages}`);
  }
}

/* ──────────────────────────────────────────────
   D. Rejection still happens for a sheet with NO copy at all
   ────────────────────────────────────────────── */

section("D. a sheet with no recognisable copy is still rejected");

{
  const noCopy: Sheet = { ...single, cells: new Map(), maxRow: 0, maxCol: 0 };
  // Keep some invoice-ish text so the failure can only be about the missing copy.
  for (const cell of single.cells.values()) {
    if (cell.row < 20) noCopy.cells.set(`${cell.row}:${cell.col}`, cell);
  }
  let message = "";
  try {
    parseSheet(noCopy);
  } catch (err) {
    message = err instanceof Error ? err.message : String(err);
  }
  check(message !== "", "a sheet with no ORIGINAL/DUPLICATE/TRIPLICATE is rejected");
  check(
    message.includes("No ORIGINAL, DUPLICATE or TRIPLICATE invoice copy was found"),
    "the error says which copy was missing",
    message.split(".")[1]?.trim() ?? message
  );
  check(
    !/missing (DUPLICATE|TRIPLICATE)/.test(message),
    "the error no longer blames a merely-absent copy"
  );
}

/* A sheet that is not an invoice at all is still skipped, not crashed on. */
{
  const junk: Sheet = { name: "Notes", cells: new Map(), maxRow: 2, maxCol: 2 };
  junk.cells.set("0:0", { row: 0, col: 0, type: "inline", value: "Shopping list" });
  junk.cells.set("1:0", { row: 1, col: 0, type: "inline", value: "Milk" });
  const { bills, skipped } = parseBills([junk, single]);
  check(bills.length === 1, "a non-invoice sheet is skipped, the real one still parses", `${bills.length}`);
  check(
    skipped.length === 1 && skipped[0].sheetName === "Notes",
    "the non-invoice sheet is reported as skipped",
    skipped.map((s) => s.sheetName).join(", ")
  );
}

